function normalize(text) {
  return text.replace(/\r\n/g, '\n');
}

function parseSections(body) {
  const collected = {};
  let current = null;
  for (const line of normalize(body).split('\n')) {
    const heading = line.match(/^##\s+(.+?)\s*$/);
    if (heading) {
      current = heading[1];
      collected[current] = [];
    } else if (current) {
      collected[current].push(line);
    }
  }
  const result = {};
  for (const [title, lines] of Object.entries(collected)) {
    result[title] = lines.join('\n').trim();
  }
  return result;
}

function toParagraphs(text) {
  return text
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter(Boolean);
}

function toBullets(text) {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.startsWith('- '))
    .map((line) => line.slice(2).trim());
}

const ARTWORK_FIELDS = [
  'id',
  'position',
  'title',
  'artist',
  'year',
  'imageFile',
  'imageCredit',
  'medium',
  'dimensions',
  'location',
];

const ARTWORK_SECTIONS = [
  'Description',
  'Story',
  'Look closer',
  'Context',
  'Artist',
  'When this was painted',
];

function buildArtwork(data, body, source) {
  const errors = [];
  for (const field of ARTWORK_FIELDS) {
    if (data[field] === undefined || data[field] === '') {
      errors.push(`${source}: missing field "${field}"`);
    }
  }
  const sections = parseSections(body);
  for (const section of ARTWORK_SECTIONS) {
    if (!sections[section]) {
      errors.push(`${source}: missing section "## ${section}"`);
    }
  }
    if (
    sections['Look closer'] &&
    toBullets(sections['Look closer']).length === 0
  ) {
    errors.push(
      `${source}: section "Look closer" needs at least one "- " bullet`
    );
  }
  if (errors.length > 0) return { errors };

  return {
    errors,
    position: Number(data.position),
    artwork: {
      id: data.id,
      title: data.title,
      artist: data.artist,
      year: String(data.year),
      imageKey: data.id,
      imageCredit: data.imageCredit,
      description: sections['Description'],
      story: toParagraphs(sections['Story']),
      lookCloser: toBullets(sections['Look closer']),
      context: toParagraphs(sections['Context']),
      artistBio: sections['Artist'],
      artistAtTheTime: sections['When this was painted'],
      details: {
        medium: data.medium,
        dimensions: data.dimensions,
        location: data.location,
      },
    },
  };
}

function buildMovement(data, body, source) {
  const errors = [];
  for (const field of ['id', 'order', 'name', 'yearRange']) {
    if (data[field] === undefined || data[field] === '') {
      errors.push(`${source}: missing field "${field}"`);
    }
  }
  const description = normalize(body).trim();
  if (!description) {
    errors.push(`${source}: missing description (the text under the header)`);
  }
  if (errors.length > 0) return { errors };

  return {
    errors,
    movement: {
      id: data.id,
      order: Number(data.order),
      name: data.name,
      yearRange: String(data.yearRange),
      description,
    },
  };
}

function findDuplicates(label, values) {
  const seen = new Set();
  const errors = [];
  for (const value of values) {
    if (seen.has(value)) errors.push(`duplicate ${label}: ${value}`);
    seen.add(value);
  }
  return errors;
}

function renderImagesModule(imageFiles) {
  const lines = Object.keys(imageFiles)
    .sort()
    .map(
      (id) => `  '${id}': require('../../assets/artworks/${imageFiles[id]}'),`
    );
  return [
    '// AUTO-GENERATED by scripts/build-content.js. Do not edit by hand.',
    "import { ImageSourcePropType } from 'react-native';",
    '',
    'export const images: Record<string, ImageSourcePropType> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

